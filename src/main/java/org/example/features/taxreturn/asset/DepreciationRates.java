    private static final Map<Integer, BigDecimal[]> RATES = load();

    private DepreciationRates() {}

    private static Map<Integer, BigDecimal[]> load() {
        Map<Integer, BigDecimal[]> result = new HashMap<>();
        TABLE.lines().forEach(line -> {
            String[] fields = line.strip().split(",");
            BigDecimal[] values = new BigDecimal[fields.length - 1];
            for (int i = 1; i < fields.length; i++) {
                values[i - 1] = new BigDecimal(fields[i]);
            }
            result.put(Integer.parseInt(fields[0]), values);
        });
        return Map.copyOf(result);
    }

    private static BigDecimal value(int life, int column) {
        BigDecimal[] values = RATES.get(life);
        if (values == null || column >= values.length) {
            throw new IllegalArgumentException("Unsupported depreciation rate: life=" + life + ", column=" + column);
        }
        return values[column];
    }

    public static BigDecimal oldStraight(int life) { return value(life, 0); }
    public static BigDecimal oldDeclining(int life) { return value(life, 1); }
    public static BigDecimal straight(int life) { return value(life, 2); }

    public static Declining declining(int life, boolean rate250) {
        int column = rate250 ? 3 : 6;
        return new Declining(value(life, column), value(life, column + 1), value(life, column + 2));
    }

    public record Declining(BigDecimal rate, BigDecimal revisedRate, BigDecimal guaranteeRate) {}
