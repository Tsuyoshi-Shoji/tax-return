CREATE TABLE fiscal_year_closing_event (
    id BIGINT NOT NULL AUTO_INCREMENT,
    fiscal_year_id BIGINT NOT NULL,
    app_user_id BIGINT NOT NULL,
    event_type VARCHAR(10) NOT NULL,
    close_version INT NOT NULL,
    reason VARCHAR(200),
    sales DECIMAL(15,2) NOT NULL,
    expenses DECIMAL(15,2) NOT NULL,
    income DECIMAL(15,2) NOT NULL,
    income_after_deduction DECIMAL(15,2) NOT NULL,
    blue_deduction INT NOT NULL,
    assets_closing DECIMAL(15,2) NOT NULL,
    liabilities_closing DECIMAL(15,2) NOT NULL,
    journal_line_count INT NOT NULL,
    debit_total DECIMAL(15,2) NOT NULL,
    credit_total DECIMAL(15,2) NOT NULL,
    data_fingerprint VARCHAR(64) NOT NULL,
    calc_rule_version VARCHAR(20) NOT NULL,
    form_edition VARCHAR(40) NOT NULL,
    occurred_at DATETIME NOT NULL,
    created_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_fiscal_year_closing_event UNIQUE (fiscal_year_id, close_version, event_type),
    CONSTRAINT chk_fiscal_year_closing_event_type CHECK (event_type IN ('CLOSE', 'REOPEN')),
    CONSTRAINT chk_fiscal_year_closing_event_version CHECK (close_version >= 1),
    CONSTRAINT fk_fiscal_year_closing_event_year FOREIGN KEY (fiscal_year_id) REFERENCES fiscal_year (id),
    CONSTRAINT fk_fiscal_year_closing_event_user FOREIGN KEY (app_user_id) REFERENCES app_user (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE report_output_record (
    id BIGINT NOT NULL AUTO_INCREMENT,
    fiscal_year_id BIGINT NOT NULL,
    app_user_id BIGINT NOT NULL,
    output_type VARCHAR(30) NOT NULL,
    file_name VARCHAR(120) NOT NULL,
    file_sha256 VARCHAR(64) NOT NULL,
    file_size BIGINT NOT NULL,
    data_fingerprint VARCHAR(64) NOT NULL,
    calc_rule_version VARCHAR(20) NOT NULL,
    form_edition VARCHAR(40) NOT NULL,
    year_status VARCHAR(10) NOT NULL,
    close_version INT,
    record_status VARCHAR(20) NOT NULL,
    cancel_reason VARCHAR(200),
    cancelled_at DATETIME,
    generated_at DATETIME NOT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT chk_report_output_record_status CHECK (record_status IN ('CURRENT', 'SUPERSEDED', 'CANCELLED')),
    CONSTRAINT chk_report_output_record_year_status CHECK (year_status IN ('open', 'closed')),
    CONSTRAINT fk_report_output_record_year FOREIGN KEY (fiscal_year_id) REFERENCES fiscal_year (id),
    CONSTRAINT fk_report_output_record_user FOREIGN KEY (app_user_id) REFERENCES app_user (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE INDEX idx_report_output_record_year ON report_output_record (fiscal_year_id, generated_at);
